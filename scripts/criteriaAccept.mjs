// Acknowledge a change to the app's criteria (see scripts/criteria.mjs).
//   npm run criteria:accept -- "why this rule changed"
// Updates scripts/criteria.lock.json and appends a dated entry to docs/CRITERIA_CHANGELOG.md listing exactly which rules, functions
// and files were added / changed / removed. `npm run verify:invariants` fails until this has been run for every criteria change.
import { readFileSync, writeFileSync, existsSync, appendFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { collectCriteria } from "./criteria.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const reason = process.argv.slice(2).join(" ").trim();
const lockPath = join(root, "scripts/criteria.lock.json");
const logPath = join(root, "docs/CRITERIA_CHANGELOG.md");
const { criteria, missing } = collectCriteria(root);
if (missing.length) { console.error("Cannot accept: these tracked items were not found:\n  " + missing.join("\n  ")); process.exit(1); }
const old = existsSync(lockPath) ? JSON.parse(readFileSync(lockPath, "utf8")).criteria || {} : {};
const added = Object.keys(criteria).filter((k) => !(k in old));
const removed = Object.keys(old).filter((k) => !(k in criteria));
const changed = Object.keys(criteria).filter((k) => k in old && old[k] !== criteria[k]);
if (!added.length && !removed.length && !changed.length) { console.log("Nothing changed -- lock already matches the code."); process.exit(0); }
if (!reason && Object.keys(old).length) { console.error("Say WHY: npm run criteria:accept -- \"reason for this change\"\n\nChanged: " + [...changed, ...added, ...removed].join(", ")); process.exit(1); }
writeFileSync(lockPath, JSON.stringify({ note: "Generated by scripts/criteriaAccept.mjs -- do not edit by hand.", criteria }, null, 1) + "\n");
mkdirSync(dirname(logPath), { recursive: true });
if (!existsSync(logPath)) writeFileSync(logPath, "# Criteria change log\n\nEvery change to a rule, condition, function or config file the app depends on, newest last. Written by `npm run criteria:accept`.\n");
const date = new Date().toISOString().slice(0, 10);
const MAXN = 40;
const list = (t, a) => (a.length ? `- ${t} (${a.length}): ${a.slice(0, MAXN).join(", ")}${a.length > MAXN ? `, ... +${a.length - MAXN} more (see git diff of scripts/criteria.lock.json)` : ""}\n` : "");
appendFileSync(logPath, `\n## ${date} -- ${reason || "initial baseline"}\n${list("changed", changed)}${list("added", added)}${list("removed", removed)}`);
console.log(`Lock updated: ${changed.length} changed, ${added.length} added, ${removed.length} removed. Logged in docs/CRITERIA_CHANGELOG.md`);
